// Writes _data/images.yml (width/height of every JPEG in assets/images) for _includes/figure.html.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'images');

function jpegSize(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) throw new Error('bad marker');
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  throw new Error('no SOF marker');
}

const lines = ['# Generated by scripts/image-sizes.mjs: image sizes for _includes/figure.html'];
for (const f of readdirSync(dir).filter((n) => n.endsWith('.jpg')).sort()) {
  const { w, h } = jpegSize(readFileSync(join(dir, f)));
  lines.push(`"${f.replace(/\.jpg$/, '')}": { w: ${w}, h: ${h} }`);
}
writeFileSync(join(root, '_data', 'images.yml'), lines.join('\n') + '\n');
console.log(`${lines.length - 1} images`);
